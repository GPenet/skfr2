int tcellsrcb[81], tcellsrcb3[81][3];
void BuildTrcb() {
	for (int i = 0; i < 81; i++) {
		int r = i / 9, c = i % 9, b = 3 * (r / 3) +  (c / 3);
		tcellsrcb[i] = (1 << r) | (1 << (c + 9)) | (1 << (b + 18));
		tcellsrcb3[i][0]=r; 
		tcellsrcb3[i][1] = c+9;
		tcellsrcb3[i][2] = b+18;
	}
}
